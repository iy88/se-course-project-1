CREATE TABLE moderation_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_type TEXT NOT NULL CHECK (case_type <> ''),
    created_at TIMESTAMPTZ NOT NULL,
    claimed_manager_id BIGINT CHECK (claimed_manager_id > 0),
    claimed_at TIMESTAMPTZ,
    CHECK ((claimed_manager_id IS NULL) = (claimed_at IS NULL))
);

CREATE INDEX moderation_case_claim_idx ON moderation_case (claimed_manager_id, id);

CREATE TABLE moderation_case_action (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES moderation_case (id),
    action_kind TEXT NOT NULL CHECK (action_kind <> ''),
    actor_account_id BIGINT NOT NULL CHECK (actor_account_id > 0),
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX moderation_case_action_case_idx ON moderation_case_action (case_id);

-- Product review projections rely on one claim and one decision fact per case.
CREATE UNIQUE INDEX moderation_case_action_claim_once
    ON moderation_case_action (case_id) WHERE action_kind = 'claim';
CREATE UNIQUE INDEX moderation_case_action_decide_once
    ON moderation_case_action (case_id) WHERE action_kind = 'decide';
