def scenario_by_key(key: str) -> ScenarioSpec:
    for scenario in SCENARIOS:
        if scenario.key == key:
            return scenario
    raise KeyError(key)


def catalog_signature() -> str:
    """Stable catalog digest: any account, product, trade, report, notification, or scenario change alters it."""
    import hashlib
    import json
    from dataclasses import asdict

    def rows(items):
        return [asdict(item) for item in items]

    payload = {
        "version": CATALOG_VERSION,
        "accounts": rows(ACCOUNTS),
        "categories": rows(CATEGORIES),
        "prohibited": rows(PROHIBITED),
        "products": rows(PRODUCTS),
        "trades": rows(TRADES),
        "reports": rows(REPORTS),
        "restrictions": rows(RESTRICTIONS),
        "cases": rows(CASES),
        "notifications": rows(NOTIFICATIONS),
        "normal_conversations": rows(NORMAL_CONVERSATIONS),
        "avatars": rows(AVATARS),
        "scenarios": rows(SCENARIOS),
    }
    raw = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()
